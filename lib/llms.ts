    "Output: `{ name, results, summary }` where each result is `{ provider, status, subject, available, detail?, durationMs }`; `status` is `available | taken | unknown | invalid` and `available` agrees with it (`unknown` → null). Providers run concurrently with a 5-second timeout each; a failure reports `unknown`, it never fails the batch.",
